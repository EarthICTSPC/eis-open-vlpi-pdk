#!/usr/bin/env python3
"""Generate (or verify) the Lean module for EIS-CRC-BUDGET-001.

The JSON fixture is the source of truth. --check exits nonzero when the
committed Lean module is stale.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_FIXTURE = ROOT / "fixtures" / "EIS-CRC-BUDGET-001.json"
DEFAULT_OUTPUT = ROOT / "formal" / "lean4" / "EISVLPI" / "Fixtures" / "EIS_CRC_BUDGET_001.lean"


def render(fixture: dict) -> str:
    if fixture.get("timing_model") != "serial_additive" or fixture.get("latency_unit") != "ps":
        raise ValueError("Lean fixture generator requires serial_additive timing in integer ps")
    stages = fixture["stages"]
    if not stages or any(type(s.get("latency_ps")) is not int or s["latency_ps"] < 0 for s in stages):
        raise ValueError("Each stage must have a non-negative integer latency_ps")
    if type(fixture.get("budget_ps")) is not int or fixture["budget_ps"] < 0:
        raise ValueError("budget_ps must be a non-negative integer")
    names = [s["name"] for s in stages]
    latencies = [s["latency_ps"] for s in stages]
    cumulative = []
    total = 0
    for value in latencies:
        total += value
        cumulative.append(total)
    budget = fixture["budget_ps"]
    first_over = next((i for i, value in enumerate(cumulative) if value > budget), None)
    if first_over is None:
        raise ValueError("Fixture must contain a stage that exceeds the budget")
    stage_name = names[first_over]
    lean_names = ["dac", "modulator", "prism", "thresholder", "kka", "photodetector", "adc"]
    if len(names) != len(lean_names):
        raise ValueError("This fixture schema currently expects exactly seven named pipeline stages")
    if [n.lower() for n in names] != lean_names:
        raise ValueError("Unexpected EIS-CRC-BUDGET-001 stage ordering/names")
    def nat_list(values):
        return "[" + ", ".join(str(v) for v in values) + "]"
    lines = [
        "/- Generated by scripts/gen_lean_fixture.py from fixtures/EIS-CRC-BUDGET-001.json.",
        "   Do not edit manually; run the generator. JSON is the source of truth. -/",
        "namespace EISVLPI",
        "namespace Budget001",
        "",
        "abbrev Picoseconds := Nat",
        f"def stageLatencies : List Picoseconds := {nat_list(latencies)}",
        f"def cumulativeLatencies : List Picoseconds := {nat_list(cumulative)}",
        f"def budget : Picoseconds := {budget}",
        f"def expectedTotal : Picoseconds := {fixture['expected_total_ps']}",
        f"def expectedOverrun : Picoseconds := {fixture['expected_overrun_ps']}",
        f'def rejectionStage : String := "{stage_name}"',
        "",
        "def pipelineWithinBudget (latencies : List Picoseconds) (limit : Picoseconds) : Bool :=",
        "  latencies.sum <= limit",
        "",
        "theorem total_matches_fixture : stageLatencies.sum = expectedTotal := by",
        "  decide",
        "theorem total_is_228 : stageLatencies.sum = 228 := by",
        "  decide",
        "theorem total_exceeds_budget : stageLatencies.sum > budget := by",
        "  decide",
        "theorem rejected : pipelineWithinBudget stageLatencies budget = false := by",
        "  decide",
        f"theorem cumulative_at_{stage_name.lower()}_exceeds_budget : cumulativeLatencies[{first_over}]! > budget := by",
        "  decide",
    ]
    if first_over > 0:
        lines += [
            f"theorem cumulative_before_{stage_name.lower()}_within_budget : cumulativeLatencies[{first_over - 1}]! <= budget := by",
            "  decide",
        ]
    lines += [
        f'theorem rejection_stage_is_{stage_name.lower()} : rejectionStage = "{stage_name}" := by',
        "  rfl",
        "",
        "end Budget001",
        "end EISVLPI",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--fixture", type=Path, default=DEFAULT_FIXTURE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="fail if output is missing or stale")
    args = parser.parse_args()
    fixture = json.loads(args.fixture.read_text(encoding="utf-8"))
    expected = render(fixture)
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != expected:
            print(f"Generated Lean fixture is stale: {args.output}")
            return 1
        print(f"Generated Lean fixture is current: {args.output.relative_to(ROOT)}")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(expected, encoding="utf-8")
    print(f"Wrote {args.output.relative_to(ROOT)}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
